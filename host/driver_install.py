"""
ATmega16U2 DFU 장치(03EB:2FEF)에 WinUSB 드라이버를 설치한다 (libwdi wdi-simple + UAC).

언제 실행하나
  - 사용자가 대시보드의 [드라이버 자동 설치] 버튼(POST /driver/install)이나 `vm driver-install` 로 요청할 때만.
    에이전트가 시작하거나 상태를 조회할 때 스스로 실행하지 않는다.
  - DFU 장치가 연결돼 있고 WinUSB 드라이버가 아직 없을 때만 wdi-simple 을 실행한다.

어떻게 하나
  - 번들된 tools/wdi-simple/wdi-simple.exe(scripts/build_wdi.ps1 로 빌드)를 새 임시 작업 폴더에 복사하고,
    UAC(ShellExecuteEx "runas")로 관리자 권한을 얻어 그 폴더에서 실행한다. 인수는 모두 ASCII 다(--dest 는 "driver").
    wdi-simple 은 인수를 ANSI 코드 페이지로 받고, libwdi 는 상대 경로의 폴더를 exe 폴더 기준으로 만들기 때문에
    작업 폴더와 exe 폴더를 같게 두고 상대 경로를 쓴다 (사용자 이름에 한글이 있어도 된다).
  - 관리자 권한이어야 libwdi 가 드라이버 카탈로그(.cat)를 만들어 자체 서명할 수 있다. 이때 libwdi 는 서명용 인증서
    'USB\\VID_03EB&PID_2FEF (libwdi autogenerated)' 를 로컬 컴퓨터의 신뢰할 수 있는 루트·게시자 저장소에 추가하고,
    서명이 끝나면 개인 키를 지워 다른 파일에 다시 쓸 수 없게 한다 (Zadig 과 같은 방식).
  - 에이전트는 앞 창이 아니어서 UAC 창이 작업 표시줄의 깜빡이는 아이콘으로만 뜰 수 있다 (대시보드가 안내한다).

시간 제한
  - UAC 응답은 UAC_RESPONSE_TIMEOUT_SEC 까지 기다린다. 지나면 timeout(pending) 으로 답하지만, 창이 남아 있다가
    나중에 승인되면 설치가 이어진다. 그동안 on_finished 를 부르지 않아 다른 설치·펌웨어 업데이트가 끼어들지 않는다.
  - 설치 실행은 INSTALL_TIMEOUT_SEC 까지 기다린다. 지나면 프로세스를 끝내고 timeout 으로 답한다.

결과 status: installed / already_installed / cancelled(UAC 거부) / failed / timeout / no_device / unavailable

사용처: dispatcher.py(install_driver)
의존: device_status(scan_usb_devices, find_dfu_device, dfu_driver_installed), updater(_resource_root)
"""

