class ElevationCancelled(Exception):
    """UAC 창에서 사용자가 [아니요]를 눌렀다."""


class ElevatedProcess(Protocol):
    """UAC 로 시작한 프로세스 (테스트에서는 가짜로 바꾼다)."""

    def wait(self, timeout: float) -> Optional[int]:
        """끝날 때까지 최대 timeout 초 기다려 종료 코드(부호 있는 32비트)를 돌려준다. 시간 초과면 None."""

    def terminate(self) -> bool:
        """프로세스를 끝낸다. 끝냈으면 True."""

    def close(self) -> None:
        """핸들을 닫는다."""


Launcher = Callable[[str, str, str], ElevatedProcess]


def to_signed_exit_code(code: int) -> int:
    """Windows 종료 코드(DWORD)를 부호 있는 값으로 바꾼다. wdi-simple 은 음수 오류 코드를 돌려준다 (예: 0xFFFFFFF1 -> -15)."""
    code &= 0xFFFFFFFF
    return code - 0x1_0000_0000 if code >= 0x8000_0000 else code


def find_wdi_simple() -> Optional[Path]:
    """번들(또는 개발 환경)의 tools/wdi-simple/wdi-simple.exe. 없으면 None (scripts/build_wdi.ps1 로 만든다)."""
    path = _resource_root() / "tools" / "wdi-simple" / WDI_EXE_NAME
    return path if path.is_file() else None


def is_available() -> bool:
    """이 에이전트에서 드라이버 자동 설치를 쓸 수 있는지 (Windows 이고 wdi-simple 이 들어 있음)."""
    return sys.platform == "win32" and find_wdi_simple() is not None


def _result(status: str, message: str, **extra: Any) -> Dict[str, Any]:
    return {"ok": status in ("installed", "already_installed"), "status": status, "message": message, **extra}


def _scan_now() -> List[Dict[str, Any]]:
    # 캐시를 쓰지 않고 다시 조회한다 (조회 결과는 /status 캐시에도 반영된다)
    return scan_usb_devices(force=True)


if sys.platform == "win32":
    import ctypes
    from ctypes import wintypes

    class SHELLEXECUTEINFOW(ctypes.Structure):
        _fields_ = [
            ("cbSize", wintypes.DWORD),
            ("fMask", wintypes.ULONG),
            ("hwnd", wintypes.HWND),
            ("lpVerb", wintypes.LPCWSTR),
            ("lpFile", wintypes.LPCWSTR),
            ("lpParameters", wintypes.LPCWSTR),
            ("lpDirectory", wintypes.LPCWSTR),
            ("nShow", ctypes.c_int),
            ("hInstApp", wintypes.HINSTANCE),
            ("lpIDList", ctypes.c_void_p),
            ("lpClass", wintypes.LPCWSTR),
            ("hkeyClass", wintypes.HKEY),
            ("dwHotKey", wintypes.DWORD),
            ("hIconOrMonitor", wintypes.HANDLE),
            ("hProcess", wintypes.HANDLE),
        ]

    SEE_MASK_NOCLOSEPROCESS = 0x00000040
    SEE_MASK_NOASYNC = 0x00000100
    SW_HIDE = 0
    ERROR_CANCELLED = 1223
    WAIT_OBJECT_0 = 0x00000000
    WAIT_TIMEOUT = 0x00000102
    COINIT_APARTMENTTHREADED = 0x2
    COINIT_DISABLE_OLE1DDE = 0x4

    _kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    _kernel32.WaitForSingleObject.argtypes = [wintypes.HANDLE, wintypes.DWORD]
    _kernel32.WaitForSingleObject.restype = wintypes.DWORD
    _kernel32.GetExitCodeProcess.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
    _kernel32.GetExitCodeProcess.restype = wintypes.BOOL
    _kernel32.TerminateProcess.argtypes = [wintypes.HANDLE, wintypes.UINT]
    _kernel32.TerminateProcess.restype = wintypes.BOOL
    _kernel32.CloseHandle.argtypes = [wintypes.HANDLE]
    _kernel32.CloseHandle.restype = wintypes.BOOL

    class _Win32Process:
        def __init__(self, handle: int):
            self._handle = handle

        def wait(self, timeout: float) -> Optional[int]:
            rc = _kernel32.WaitForSingleObject(self._handle, max(0, int(timeout * 1000)))
            if rc == WAIT_TIMEOUT:
                return None
            if rc != WAIT_OBJECT_0:
                raise ctypes.WinError(ctypes.get_last_error())
            code = wintypes.DWORD()
            if not _kernel32.GetExitCodeProcess(self._handle, ctypes.byref(code)):
                raise ctypes.WinError(ctypes.get_last_error())
            return to_signed_exit_code(code.value)

        def terminate(self) -> bool:
            return bool(_kernel32.TerminateProcess(self._handle, 1))

        def close(self) -> None:
            if self._handle:
                _kernel32.CloseHandle(self._handle)
                self._handle = 0

    def launch_elevated(exe: str, params: str, cwd: str) -> ElevatedProcess:
        """UAC(ShellExecuteEx "runas")로 exe 를 관리자 권한으로 시작한다. 사용자가 거부하면 ElevationCancelled.

        UAC 창이 떠 있는 동안 이 함수는 돌아오지 않는다 (호출하는 쪽이 시간 제한을 둔다).
        """
        shell32 = ctypes.WinDLL("shell32", use_last_error=True)
        shell32.ShellExecuteExW.argtypes = [ctypes.POINTER(SHELLEXECUTEINFOW)]
        shell32.ShellExecuteExW.restype = wintypes.BOOL
        ole32 = ctypes.WinDLL("ole32")
        ole32.CoInitializeEx.argtypes = [ctypes.c_void_p, wintypes.DWORD]
        ole32.CoInitializeEx.restype = ctypes.c_long

        info = SHELLEXECUTEINFOW()
        info.cbSize = ctypes.sizeof(info)
        info.fMask = SEE_MASK_NOCLOSEPROCESS | SEE_MASK_NOASYNC
        info.lpVerb = "runas"
        info.lpFile = exe
        info.lpParameters = params
        info.lpDirectory = cwd
        info.nShow = SW_HIDE
        # ShellExecuteEx 는 COM 을 쓸 수 있으므로 이 스레드에서 초기화한다 (S_OK·S_FALSE 면 짝을 맞춰 해제)
        com_ready = ole32.CoInitializeEx(None, COINIT_APARTMENTTHREADED | COINIT_DISABLE_OLE1DDE) in (0, 1)
        try:
            ok = shell32.ShellExecuteExW(ctypes.byref(info))
            err = ctypes.get_last_error()
        finally:
            if com_ready:
                ole32.CoUninitialize()
        if not ok:
            if err == ERROR_CANCELLED:
                raise ElevationCancelled()
            raise ctypes.WinError(err)
        if not info.hProcess:
            raise OSError("ShellExecuteEx did not return a process handle")
        return _Win32Process(info.hProcess)

